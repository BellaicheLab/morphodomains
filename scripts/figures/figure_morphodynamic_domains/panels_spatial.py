"""Spatial tensor map scene builders for figure_morphodynamic_domains.

Each of the 11 quantities (ER, EG, EA, ED, ES, CellIaniso, dnA, dnD,
CellArea, U, Epsilon) gets its own scene builder, generated by a factory
function.  The framework handles viewer creation, exports, and lifecycle.

Exported dict:
    SPATIAL_SCENES — maps scene names to builder functions.
"""

import logging

import numpy as np
from pyanimalprocessing.plotting.napari_plotting import (
    add_tensor_legends,
    add_tensor_scale_bar,
    create_bbox_for_scale,
)
from pyanimalprocessing.plotting.property_plotting import plot_property, read_property

from scripts.figures._napari_helpers import reformat_time_legends
from scripts.figures.figure_flow_deformation._helpers import IMAGE_SIZE, add_marker_points

from .preprocessing import BBOX_X, BBOX_Y_OFFSET, QUANTITY_CONFIG, SCALE_POSITION

logger = logging.getLogger(__name__)

VECTOR_SCALE_FACTOR = 2.0


# ── Core scene builder ───────────────────────────────────────────────────────


def _build_quantity_scene(viewer, shared_data, quantity_key):
    """Build a spatial Lagrangian tensor scene for a single quantity.

    Parameters
    ----------
    viewer : napari.Viewer
        Viewer created by the dispatcher.
    shared_data : dict
        Must contain ``AOA_vi_4h``, ``animal``, ``clean_outline_spatial``,
        ``tracking_mask``, and ``available_quantities``.
    quantity_key : str
        Key into :data:`QUANTITY_CONFIG` (e.g. ``"ER"``, ``"CellIaniso"``).
    """
    config = QUANTITY_CONFIG[quantity_key]
    available = shared_data.get("available_quantities", [])
    if quantity_key not in available:
        logger.warning("Quantity %s not available in zarr, skipping", quantity_key)
        return

    AOA_vi_4h = shared_data["AOA_vi_4h"]
    animal = shared_data["animal"]
    clean_outline = shared_data["clean_outline_spatial"]
    tracking_mask = shared_data["tracking_mask"]

    # Lagrangian tensor fields overlaid onto the movie via its SAP registration.
    bundle = read_property(
        AOA_vi_4h, config["quantity_name"], reference_animal=animal,
        grid_bulk_threshold=0.15, significance=0,
        lagrangian=True, tracking_mask=tracking_mask, lagrangian_time_ref="17h40",
    )

    n_frames = bundle["property_data"].shape[0]
    start_frame = int(round(np.asarray(bundle["affine_transform"])[0, -1]))
    n_components = bundle["property_data"].shape[-1]  # 4=matrix, 2=vector, 1=scalar
    is_vector = n_components == 2

    # Fold the fig-2 vector-scale factor into vector_scale; keep scalar sizes at
    # config["scale"]; plot_property clips outliers at 2/98 pct.
    vsf = config.get("vector_scale_factor", VECTOR_SCALE_FACTOR)
    scale_value = config["scale_value"]

    viewer.add_image(clean_outline, name="outline")

    plot_property(
        **{**bundle, "property_name": config["display_name"]},
        viewer=viewer,
        vector_scale=config["scale"] * vsf,
        scalar_scale=config["scale"],
        rescale_property="Rotation",
        clipping_percentile=(0.02, 0.98),
        vectors_kwargs={
            "edge_color": config["color"],
            "vector_style": config["vector_style"],
            "edge_width": config.get("linewidth", 8),
            "opacity": 1,
        },
    )

    # Reference scale bar (single ``scale`` covers both the vector — length
    # pre-multiplied by vsf to match vector_scale — and the scalar point).
    add_tensor_scale_bar(
        viewer,
        position=SCALE_POSITION,
        length=scale_value * vsf,
        scale=config["scale"],
        n_frames=n_frames,
        color=config["color"],
        vector_style=config["vector_style"],
        edge_width=config.get("linewidth", 8),
        start_frame=start_frame,
        scalar=None if is_vector else scale_value,
    )

    add_tensor_legends(
        viewer,
        time_array=AOA_vi_4h.attrs["TimeArray"],
        image_size=IMAGE_SIZE,
        quantity=config["display_name"],
        start_frame=start_frame,
        quantity_color=config["color"],
        quantity_anchor="lower_left",
        quantity_translation=[-250, 50],
        time_color="black",
        time_anchor="lower_left",
        time_translation=[-130, 50],
        legend_size=80,
    )

    # Scale-bar text label (fig-2 keeps its own add_shapes legend box).
    _add_scale_bar_legend(viewer, config)

    # Macrochaete markers (also converts every Points layer to Shapes).
    add_marker_points(viewer)

    # For matrix quantities, show only the positive-eigenvalue (extension / positive CE
    # rate) deviatoric bar, and draw it in front of the iso circles —
    # convert_points_to_shapes re-appends the circles last, so without this the bars
    # would sit behind them.
    neg_name = f"{config['display_name']}_negative"
    pos_name = f"{config['display_name']}_positive"
    if neg_name in viewer.layers:
        viewer.layers.remove(viewer.layers[neg_name])
    if pos_name in viewer.layers:
        viewer.layers.move(viewer.layers.index(viewer.layers[pos_name]), len(viewer.layers) - 1)

    viewer.dims.set_point(0, 94)

    reformat_time_legends(viewer)
    logger.info("Scene for %s ready", quantity_key)


# ── Scale bar label helper ────────────────────────────────────────────────────


def _add_scale_bar_legend(viewer, config):
    """Add the fig-2 scale-bar text label box (add_shapes)."""
    scale_value = config.get("scale_value")
    if not scale_value:
        return

    bbox = create_bbox_for_scale(SCALE_POSITION, BBOX_X, BBOX_Y_OFFSET)

    features = {"length": [scale_value]}
    text_properties = {
        "string": f"{{length}} {config.get('unit', '')}",
        "anchor": "center",
        "size": 80,
        "color": config.get("color", "black"),
        "translation": [0, -20],
    }

    viewer.add_shapes(
        bbox,
        features=features,
        text=text_properties,
        face_color="transparent",
        edge_color="transparent",
        name="scale legend",
    )


# ── Factory ──────────────────────────────────────────────────────────────────


def _make_quantity_scene_builder(quantity_key):
    """Create a scene builder function for a specific quantity."""

    def build_scene(viewer, shared_data):
        _build_quantity_scene(viewer, shared_data, quantity_key)

    build_scene.__name__ = f"build_spatial_{quantity_key}_scene"
    return build_scene


SPATIAL_SCENES = {
    f"build_spatial_{qty}_scene": _make_quantity_scene_builder(qty)
    for qty in QUANTITY_CONFIG
}
